export const PARAMS_VERSION = '2026-08-21.3'

/**
 * 異動紀錄
 *
 * - 2026-08-21.1  初版。本金 50,000（§13.2 實測：低於 14,036/批 會撞到最低手續費）。
 *                 手續費不打折、最低 20 元——保守值，券商折數確認後再改。
 *
 * - 2026-08-21.2  加入 `armResetK`。**這是修正讀錯規格，不是調參數。**
 *
 *   初版把「%b<0.5 且 K<30 且金叉」全部要求在**同一天**成立，結果是
 *   四條線在真實資料上幾乎不相交。實測 115～128 個交易日：
 *
 *       標的    觸及加碼區  %b<0.5  K<30  金叉  四者同日皆是
 *       0050        46        42      6    11        0
 *       2330        53        34     12    12        0
 *       2454        27        25      5     8        0
 *       NVDA        73        57     30    10        2
 *       PLTR        78        68     30    12        4
 *
 *   台股三檔**半年一次都沒進場**。一條永遠不觸發的規則不能當 AI 的對照組，
 *   它只是一條水平線。
 *
 *   §4 的原文是「等 KD 回低檔（K<30）出現金叉**再**分批進場」——「再」是先後。
 *   改成：低檔金叉先把訊號**架起來**，之後價格回到加碼區才進場，
 *   訊號在 K 進入高檔（>70）或止損時解除。
 *
 *   這不是為了讓曲線好看而調的（§11 明令禁止），是原本的實作讀錯了規格。
 *
 * - 2026-08-21.3  「回低檔」與「出現金叉」是**兩個先後事件**，不是同一天的條件。
 *
 *   2026-08-21.2 之後美股會進場了，台股三檔仍然一次都沒有。查下去發現：
 *   K 確實有跌到低檔（0050 最低 20.5、2330 最低 15.1、2454 最低 20.6），
 *   但**金叉發生時 K 已經回到 30 以上**——上升趨勢裡 KD 的回檔又淺又快，
 *   「金叉當天 K 還低於 30」這件事在台股這半年從未發生過（架起 0 次）。
 *
 *   §4 的原文是「等 KD **回低檔（K<30）** 出現金叉再分批進場」。
 *   「回低檔」描述的是**先前那段回檔**，「出現金叉」是**之後**的轉折訊號。
 *   改成：K 曾經跌破 `addMaxK` → 記下「回過低檔」；之後出現金叉 → 架起訊號。
 *
 *   **到此為止。** 再放寬就不是讀規格而是為了讓它成交，那是 §11 禁止的事。
 *   如果這樣台股還是不進場，那是規則的實測結果，要照實報告，不是繼續改條件。
 */

/** 預設本金（台幣）。台股美股一致，兩邊同額報酬率才能並排比較（§13.2 定案） */
export const DEFAULT_CAPITAL_TWD = 50_000

export interface FeeParams {
  /** 台股手續費率，證交所公定 0.1425% */
  twFeeRate: number
  /** 券商折扣。1 = 不打折。電子下單常見 6 折，確認後改這裡 */
  twFeeDiscount: number
  /** 台股單筆最低手續費。**這是本金門檻的來源**，見 §13.2 */
  twMinFee: number
  /** 台股 ETF 證交稅 */
  twTaxEtf: number
  /** 台股個股證交稅 */
  twTaxStock: number
  /** 美股手續費率。假設用零手續費券商（複委託會完全不同，在假設裡揭露） */
  usFeeRate: number
  /** 美股最低手續費 */
  usMinFee: number
}

