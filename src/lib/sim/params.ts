export interface RuleParams {
  /**
   * 止損要不要生效。**只給 `scripts/experiment.ts` 用，正式跑一律是 true。**
   *
   * 存在的理由是 §11 的問句：「跌破止跌就出清」到底幫了還是害了？
   * 那個問題只能用「同一段資料、只差這一條規則」來回答，
   * 而不是靠讀規格或看單一檔的曲線猜。
   */
  useStop?: boolean
  /**
   * 加碼／減碼要不要掛限價。**只給 `scripts/experiment-limit.ts` 用，
   * 正式跑一律是 true（也就是不設）。**
   *
   * 存在的理由跟 `useStop` 一樣：「訊號價與成交價對不起來」到底害了多少，
   * 只能用「同一段資料、只差這一條」來回答。false 就退回舊行為——
   * 一律隔天開盤市價成交。
   */
  useLimit?: boolean
  /** 分幾批進場。**這些是猜的**，跟 §4 的 k=3 一樣，驗收場是資金曲線本身 */
  batches: number
  /** 觸及賣出區時賣掉持股的多少。§4 的用詞是「減碼」不是出清 */
  trimFraction: number
  /** 止損後幾個交易日內不重新進場。沒有冷卻的話跌破當天就會再進場，來回被巴 */
  cooldownDays: number
  /** 加碼的附帶條件：%b 要低於這個值（§4） */
  addMaxPctB: number
  /**
   * 「回低檔」的門檻。K 曾經跌破這個值，才算數過一次回檔——
   * 之後出現的金叉才是有效的進場訊號（§4）。
   */
  addMaxK: number
  /**
   * 低檔金叉之後，這個訊號還算數多久——用 K 值判斷，不是用天數。
   *
   * §4 的原文是「等 KD 回低檔（K<30）出現金叉**再**分批進場」。「再」是先後，
   * 不是同一天：金叉先發生，之後價格回到加碼區才進場。實測證明這個差別是致命的，
   * 見下方異動紀錄 2026-08-21.2。
   *
   * 訊號在 K 進入高檔時失效——那時這一段已經走完了。70 沿用
   * `verdict.ts` 既有的高檔定義，不是為了這裡新挑的數字。
   */
  armResetK: number
  /**
   * 底倉：這筆錢有多少比例是**一開始就進場**的，不等訊號。
   *
   * ## 為什麼會有這個東西
   *
   * 現行規則從 100% 現金起手，四個條件同時成立才進場。實測到目前為止
   * （六檔、約八個交易日、12 個規則帳戶）**總共只出手過一次**，AI 零次。
   * 那不是保守，那是這筆錢從頭到尾沒有在市場上——而「規劃給這一檔的錢」
   * 全程放在現金，跟沒有規劃它是同一件事。
   *
   * §4 的用詞本身就是線索：**加碼**與**減碼**都是部位調整，
   * 而你沒辦法從零減碼。用這組詞寫成的規則，預設狀態應該是「有部位」，
   * 規則負責的是**多少**，不是**要不要**。從零起手很可能跟前兩次一樣，
   * 是把規格讀成了另一件事。
   *
   * ## 但這個值不能用「哪個數字曲線最好看」來挑
   *
   * 那正是 §11 禁止的事。它是**設計決定**：這筆錢有多少比例是長期部位、
   * 多少是留給規則調節的。0 代表「全部聽訊號」，1 代表「買了不動」。
   * 中間的值要用它對「在市天數」與「超額報酬」的影響來討論，
   * 而不是挑報酬率最高的那個。
   *
   * 預設 0 = 現行行為。改成非 0 之前先跑 `npm run experiment:core`。
   */
  coreFraction?: number
}

